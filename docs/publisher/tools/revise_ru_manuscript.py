def clean_inline_markup(text: str) -> str:
    text = re.sub(r"^#{1,6}\s+", "", text.strip())
    text = re.sub(r"[*_`]", "", text)
    text = re.sub(r"\\([\[\]()>_.-])", r"\1", text)
    return re.sub(r"\s+", " ", text).strip().rstrip(":")


def normalize_mermaid(code: str) -> str:
    code = re.sub(r"\\([\[\](){}/_.|<>-])", r"\1", code)
    return code.replace("--\\>", "-->").replace("-.-\\>", "-.->")


def is_mermaid_statement(line: str) -> bool:
    value = line.strip()
    if not value:
        return True
    if value.startswith(
        (
            "flowchart ",
            "graph ",
            "subgraph ",
            "direction ",
            "style ",
            "classDef ",
            "class ",
            "linkStyle ",
            "click ",
            "%%",
        )
    ):
        return True
    if value == "end":
        return True
    return any(token in value for token in ("-->", "--\\>", "-.->", "-.\\->", "==>"))


def replace_mermaid_blocks(text: str, visual_dir: str) -> tuple[str, list[dict[str, object]]]:
    lines = text.splitlines()
    output: list[str] = []
    manifest: list[dict[str, object]] = []
    index = 0
    i = 0

    while i < len(lines):
        if not re.match(r"^(?:flowchart|graph)\s+", lines[i].strip()):
            output.append(lines[i])
            i += 1
            continue

        start = i
        block: list[str] = []
        while i < len(lines) and is_mermaid_statement(lines[i]):
            block.append(lines[i])
            i += 1
        while block and not block[-1].strip():
            block.pop()

        index += 1
        previous = next((item for item in reversed(output) if item.strip()), "Схема")
        caption = clean_inline_markup(previous)
        if len(caption) > 180:
            caption = f"Схема управления агентом {index}"
        filename = f"ru-inline-diagram-{index:02d}.png"
        image_line = f"![{caption}]({visual_dir}/{filename})"
        output.extend([image_line, ""])
        manifest.append(
            {
                "number": index,
                "source_line": start + 1,
                "caption": caption,
                "filename": filename,
                "markdown_image": image_line,
                "raw_text": "\n".join(block),
                "mermaid": normalize_mermaid("\n".join(block)),
            }
        )

    if index != 24:
        raise ValueError(f"Expected 24 Mermaid blocks, found {index}")
    return "\n".join(output).rstrip() + "\n", manifest


def replace_front_matter_and_introduction(text: str) -> str:
    author_marker = "## Об авторе"
    intro_marker = "## Введение. Зачем эта книга нужна"
    body_marker = "# Часть I. От демо-агента к платформе"

    if author_marker not in text or intro_marker not in text or body_marker not in text:
        raise ValueError("Required front-matter markers are missing")

    author_start = text.index(author_marker)
    intro_start = text.index(intro_marker)
    body_start = text.index(body_marker)
    title = text.splitlines()[0].strip()
    author_block = text[author_start:intro_start].strip()
    return f"{title}\n\n{author_block}\n\n{INTRODUCTION.strip()}\n\n{text[body_start:]}"


def normalize_headings(text: str) -> str:
    output: list[str] = []
    for line in text.splitlines():
        if re.fullmatch(r"#{1,6}\s*(?:\*+)?\s*", line):
            continue

        exercise = re.fullmatch(r"#\s+\*\*Практическое упражнение части (.+?)\*\*", line)
        if exercise:
            output.append(f"## Практическое упражнение части {exercise.group(1)}")
            continue

        conclusion = re.fullmatch(r"#\s+\*\*(Заключение\..+?)\*\*", line)
        if conclusion:
            output.append(f"# {conclusion.group(1)}")
            continue

        heading = re.fullmatch(r"(#{1,6})\s+(.+)", line)
        if heading:
            title = clean_inline_markup(heading.group(2))
            if title in GENERIC_HEADINGS:
                label = (
                    "Связь со следующей главой" if title == "Переход к следующей теме" else title
                )
                output.append(
                    f"**{label}.**" if label == "Связь со следующей главой" else f"**{label}**"
                )
                continue
            if title == "Мост зрелости":
                output.append("### Мост зрелости")
                continue
            if title == "Три сценария после полного маршрута":
                output.append("## Три сценария после полного маршрута")
                continue

        output.append(line)
    return "\n".join(output).rstrip() + "\n"


def remove_near_duplicate_blocks(text: str) -> str:
    blocks = re.split(r"(\n\s*\n)", text)
    seen_cross_references: set[str] = set()
    result: list[str] = []

    for block in blocks:
        if re.fullmatch(r"\n\s*\n", block):
            result.append(block)
            continue
        normalized = clean_inline_markup(block)
        words = normalized.split()
        is_cross_reference = (
            len(words) >= 12 and block.lstrip().startswith("*") and block.count("* Глава") >= 2
        )
        if is_cross_reference and normalized in seen_cross_references:
            continue
        result.append(block)
        if is_cross_reference:
            seen_cross_references.add(normalized)
    return "".join(result)


def link_source_list(text: str) -> str:
    pattern = re.compile(r"^(\*\s+)([^\n\[]+?)\s+\((https://[^)]+)\)\s*$", re.MULTILINE)

    def replacement(match: re.Match[str]) -> str:
        label = match.group(2).strip()
        if label.startswith("OpenReview,"):
            label = label.replace("OpenReview,", "OpenReview (препринт),", 1)
        return f"{match.group(1)}[{label}]({match.group(3)}), дата обращения: 13 июля 2026 года."

    return pattern.sub(replacement, text)


def insert_telemetry_clarification(text: str) -> str:
    anchor = (
        "Этот пример нарочно простой. Его задача не заменить SDK трассировки, "
        "а показать принцип: каждый важный шаг должен оставлять после себя "
        "структурированный след."
    )
    addition = (
        "\n\nСтатус спана и исход операции нельзя смешивать. Если обертка вызова "
        "завершилась без исключения, но инструмент вернул структурированный "
        "результат `failed`, спан не должен выглядеть как успешное действие. "
        "Либо его `status` отражает итог операции, либо событие дополнительно "
        "несет `operation_status` и `result_class`. Иначе расследование увидит "
        "зеленый спан внутри неуспешного запуска и потеряет причину отказа."
    )
    if anchor not in text:
        raise ValueError("Telemetry clarification anchor is missing")
    return text.replace(anchor, anchor + addition, 1)


def condense_dense_reference_paragraphs(text: str) -> str:
    output: list[str] = []
    replaced: set[str] = set()

    def comparison_text(value: str) -> str:
        return clean_inline_markup(re.sub(r"\\(.)", r"\1", value))

    for line in text.splitlines():
        normalized = comparison_text(line)
        replacement = next(
            (
                value
                for prefix, value in DENSE_PARAGRAPH_REPLACEMENTS.items()
                if normalized.startswith(comparison_text(prefix))
            ),
            None,
        )
        if replacement is None:
            output.append(line)
            continue

        prefix = next(
            prefix
            for prefix in DENSE_PARAGRAPH_REPLACEMENTS
            if normalized.startswith(comparison_text(prefix))
        )
        replaced.add(prefix)
        output.extend(replacement.splitlines())

    missing = set(DENSE_PARAGRAPH_REPLACEMENTS) - replaced
    if missing:
        raise ValueError(f"Dense reference paragraphs are missing: {sorted(missing)}")
    return "\n".join(output).rstrip() + "\n"


def revise(source: Path, output: Path, manifest_path: Path) -> None:
    text = source.read_text(encoding="utf-8")
    text = replace_front_matter_and_introduction(text)
    for old, new in TEXT_REPLACEMENTS.items():
        text = text.replace(old, new)
    for old, new in URL_REPLACEMENTS.items():
        text = text.replace(old, new)
    text = normalize_headings(text)
    text = remove_near_duplicate_blocks(text)
    text = link_source_list(text)
    text = insert_telemetry_clarification(text)
    text = condense_dense_reference_paragraphs(text)
    text, manifest = replace_mermaid_blocks(text, "visuals")

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="utf-8")
    manifest_path.write_text(
        json.dumps(
            {"source": str(source), "output": str(output), "diagrams": manifest},
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build the cleaned Russian publisher manuscript")
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--manifest", type=Path, required=True)
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
    revise(args.source, args.output, args.manifest)

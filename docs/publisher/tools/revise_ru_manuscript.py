def clean_inline_markup(text: str) -> str:
    text = re.sub(r"^#{1,6}\s+", "", text.strip())
    text = re.sub(r"[*_`]", "", text)
    text = re.sub(r"\\([\[\]()>_.-])", r"\1", text)
    return re.sub(r"\s+", " ", text).strip().rstrip(":")


def normalize_mermaid(code: str) -> str:
    code = re.sub(r"\\([\[\](){}/_.|<>-])", r"\1", code)
    return code.replace("--\\>", "-->").replace("-.-\\>", "-.->")


def is_mermaid_statement(line: str) -> bool:
    value = line.strip()
    if not value:
        return True
    if value.startswith(
        (
            "flowchart ",
            "graph ",
            "block-beta",
            "columns ",
            "subgraph ",
            "direction ",
            "style ",
            "classDef ",
            "class ",
            "linkStyle ",
            "click ",
            "%%",
        )
    ):
        return True
    if value == "end":
        return True
    if value == "space" or re.fullmatch(
        r"[A-Za-z_][A-Za-z0-9_-]*\s*(?:\[[^\]]*\]|\([^)]*\)|\{\{.*\}\})(?::\d+)?",
        value,
    ):
        return True
    return any(token in value for token in ("-->", "--\\>", "-.->", "-.\\->", "==>"))


def replace_mermaid_blocks(text: str, visual_dir: str) -> tuple[str, list[dict[str, object]]]:
    lines = text.splitlines()
    output: list[str] = []
    manifest: list[dict[str, object]] = []
    index = 0
    i = 0

    while i < len(lines):
        if not re.match(r"^(?:(?:flowchart|graph)\s+|block-beta$)", lines[i].strip()):
            output.append(lines[i])
            i += 1
            continue

        start = i
        block: list[str] = []
        while i < len(lines) and is_mermaid_statement(lines[i]):
            block.append(lines[i])
            i += 1
        while block and not block[-1].strip():
            block.pop()

        index += 1
        previous = next((item for item in reversed(output) if item.strip()), "Схема")
        caption = clean_inline_markup(previous)
        if len(caption) > 180:
            caption = f"Схема управления агентом {index}"
        filename = f"ru-inline-diagram-{index:02d}.png"
        image_line = f"![{caption}]({visual_dir}/{filename})"
        output.extend([image_line, ""])
        manifest.append(
            {
                "number": index,
                "source_line": start + 1,
                "caption": caption,
                "filename": filename,
                "markdown_image": image_line,
                "raw_text": "\n".join(block),
                "mermaid": normalize_mermaid("\n".join(block)),
            }
        )

    if index != 29:
        raise ValueError(f"Expected 29 Mermaid blocks, found {index}")
    return "\n".join(output).rstrip() + "\n", manifest



def convert_pseudo_tables_to_lists(text: str) -> str:
    lines = text.splitlines()
    output: list[str] = []
    converted = 0
    index = 0
    target_headers = {"Ситуация", "Угроза", "Поле каталога", "Вопрос", "Event type"}

    def cells(line: str) -> list[str]:
        return [value.strip() for value in line.strip().strip("|").split("|")]

    while index < len(lines):
        if not lines[index].strip().startswith("|") or cells(lines[index])[0] not in target_headers:
            output.append(lines[index])
            index += 1
            continue

        table: list[str] = [lines[index]]
        index += 1
        while index < len(lines):
            if not lines[index].strip():
                lookahead = index + 1
                while lookahead < len(lines) and not lines[lookahead].strip():
                    lookahead += 1
                if lookahead < len(lines) and lines[lookahead].strip().startswith("|"):
                    index = lookahead
                    continue
                break
            if not lines[index].strip().startswith("|"):
                break
            table.append(lines[index])
            index += 1

        headers = cells(table[0])
        separator = cells(table[1])
        if len(headers) < 2 or len(separator) != len(headers) or not all(
            re.fullmatch(r"\\?:?-{3,}:?", value) for value in separator
        ):
            output.extend(table)
            continue

        converted += 1
        event_table = headers[0] == "Event type"
        labels = {
            "Event type": "Тип события",
            "Когда появляется": "Когда",
            "Зачем нужен": "Назначение",
        }
        headers = [labels.get(header, header) for header in headers]
        for row in table[2:]:
            values = [
                value.replace(r"\_", "_").replace(r"\-", "-") for value in cells(row)
            ]
            if len(values) != len(headers):
                raise ValueError(f"Malformed pseudo-table row: {row}")
            lead = f"`{values[0]}`" if event_table else f"**{values[0].rstrip('.')}**"
            details = "; ".join(
                f"{header.lower()}: {value}" for header, value in zip(headers[1:], values[1:])
            )
            output.append(f"* {lead} — {details.rstrip('.')}.")
        output.append("")

    if converted != 5:
        raise ValueError(f"Expected 5 pseudo-tables, converted {converted}")
    return "\n".join(output).rstrip() + "\n"


def insert_figure_references(text: str) -> str:
    caption_pattern = re.compile(r"^Рисунок (\d+)\\?\.\s+(.+)$")
    output: list[str] = []
    referenced: list[int] = []
    for line in text.splitlines():
        match = caption_pattern.match(line)
        if match:
            number = int(match.group(1))
            title = match.group(2).strip().rstrip(".")
            output.extend(
                [f"На рисунке {number} представлена схема «{title}».", ""]
            )
            referenced.append(number)
        output.append(line)

    if referenced != list(range(1, 26)):
        raise ValueError(f"Unexpected numbered figures: {referenced}")
    return "\n".join(output).rstrip() + "\n"



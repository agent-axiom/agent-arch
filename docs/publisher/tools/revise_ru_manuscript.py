    text = repair_key_pseudocode(text)
    text = upgrade_practical_path(text)
    text = recompose_chapter_endings(text)
    text = cleanup_appendix_transitions(text)
    text = restore_incident_playbook_intro(text)
    text, manifest = replace_mermaid_blocks(text, "visuals")
    text = insert_figure_references(text)

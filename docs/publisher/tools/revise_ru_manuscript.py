def condense_dense_reference_paragraphs(text: str) -> str:
    output: list[str] = []
    replaced: set[str] = set()

    def comparison_text(value: str) -> str:
        return clean_inline_markup(re.sub(r"\\(.)", r"\1", value))

    for line in text.splitlines():
        normalized = comparison_text(line)
        replacement = next(
            (
                value
                for prefix, value in DENSE_PARAGRAPH_REPLACEMENTS.items()
                if normalized.startswith(comparison_text(prefix))
            ),
            None,
        )
        if replacement is None:
            output.append(line)
            continue

        prefix = next(
            prefix
            for prefix in DENSE_PARAGRAPH_REPLACEMENTS
            if normalized.startswith(comparison_text(prefix))
        )
        replaced.add(prefix)
        output.extend(replacement.splitlines())

    missing = set(DENSE_PARAGRAPH_REPLACEMENTS) - replaced
    if missing:
        raise ValueError(f"Dense reference paragraphs are missing: {sorted(missing)}")
    return "\n".join(output).rstrip() + "\n"


def replace_between(text: str, start: str, end: str, replacement: str) -> str:
    start_index = text.find(start)
    if start_index < 0:
        raise ValueError(f"Start marker is missing: {start}")
    end_index = text.find(end, start_index + len(start))
    if end_index < 0:
        raise ValueError(f"End marker is missing after {start}: {end}")
    return text[:start_index] + replacement.rstrip() + "\n\n" + text[end_index:]



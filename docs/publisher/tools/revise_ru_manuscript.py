def recompose_chapter_endings(text: str) -> str:
    rubric_pattern = re.compile(
        r"(?ms)^\*\*(?:Практическая проверка|Связь со следующей главой\.|"
        r"Сопутствующие материалы)\*\*\s*\n.*?"
        r"(?=^#{2,4}\s|^\*\*(?:Практическая проверка|"
        r"Связь со следующей главой\.|Сопутствующие материалы)\*\*|\Z)"
    )
    chapter_pattern = re.compile(
        r"(?ms)^## Глава (\d+)\\\..*?"
        r"(?=^## Глава \d+\\\.|^# Часть |^## Практическое упражнение|"
        r"^# Заключение|^# Приложения|\Z)"
    )

    seen: set[int] = set()

    def replacement(match: re.Match[str]) -> str:
        number = int(match.group(1))
        if number not in CHAPTER_ENDINGS:
            raise ValueError(f"Chapter ending is missing: {number}")
        seen.add(number)
        chapter = rubric_pattern.sub("", match.group(0)).rstrip()
        takeaway, practice, next_step = CHAPTER_ENDINGS[number]
        return (
            f"{chapter}\n\n### Итог главы\n\n{takeaway}\n\n"
            f"Практический шаг: {practice}\n\nДальше: {next_step}\n\n"
        )

    text = chapter_pattern.sub(replacement, text)
    missing = set(CHAPTER_ENDINGS) - seen
    if missing:
        raise ValueError(f"Chapters were not recomposed: {sorted(missing)}")
    return text.rstrip() + "\n"



    for old, new in URL_REPLACEMENTS.items():
        text = text.replace(old, new)
    text = normalize_headings(text)
    text = remove_near_duplicate_blocks(text)
    text = link_source_list(text)
    text = insert_telemetry_clarification(text)
    text = condense_dense_reference_paragraphs(text)
    text = remove_overloaded_reference_sections(text)
    text = insert_part_openers(text)
    text = remove_repeated_editorial_scaffolding(text)
    text = label_technical_examples(text)

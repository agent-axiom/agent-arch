def normalize_inline(text: str) -> str:
    text = text.strip()
    text = re.sub(r"\\([.\-])", r"\1", text)
    text = re.sub(r"\s+", " ", text)
    return text


def parse_chapters(manuscript: str) -> list[dict[str, object]]:
    matches = list(
        re.finditer(
            r"^## Глава (\d+)\\?\.\s+(.+)$",
            manuscript,
            flags=re.MULTILINE,
        )
    )
    chapters: list[dict[str, object]] = []
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(manuscript)
        body = manuscript[match.end() : end]

        outcome_match = re.search(
            r"^\*\*После главы вы сможете:\*\*\s*\n(?P<body>.*?)(?=^\*\*Артефакт главы:\*\*)",
            body,
            flags=re.MULTILINE | re.DOTALL,
        )
        outcomes = (
            [
                normalize_inline(line[2:])
                for line in outcome_match.group("body").splitlines()
                if line.startswith("* ")
            ]
            if outcome_match
            else []
        )
        artifact_match = re.search(
            r"^\*\*Артефакт главы:\*\*\s*(.+)$",
            body,
            flags=re.MULTILINE,
        )
        practice_match = re.search(
            r"^\*\*Практический шаг\.\*\*\s*(.+)$",
            body,
            flags=re.MULTILINE,
        )
        listings = re.findall(r"^\*\*Листинг \d+\.\s*([^*]+)", body, re.MULTILINE)
        labs = re.findall(r"^### Лабораторная работа \d+\\?\.\s*(.+)$", body, re.MULTILINE)
        tables = re.findall(r"^Таблица \d+\\?\.\s*(.+)$", body, re.MULTILINE)

        chapters.append(
            {
                "number": int(match.group(1)),
                "title": normalize_inline(match.group(2)),
                "outcomes": outcomes,
                "artifact": normalize_inline(artifact_match.group(1)) if artifact_match else "",
                "practice": normalize_inline(practice_match.group(1)) if practice_match else "",
                "listings": [normalize_inline(item.rstrip(". ")) for item in listings],
                "labs": [normalize_inline(item) for item in labs],
                "tables": [normalize_inline(item) for item in tables],
            }
        )
    if [chapter["number"] for chapter in chapters] != list(range(1, 29)):
        raise ValueError("Expected chapters 1 through 28 in the canonical manuscript")
    return chapters



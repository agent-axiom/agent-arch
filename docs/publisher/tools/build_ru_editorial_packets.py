def build_learning_map(chapters: list[dict[str, object]]) -> str:
    lines = [
        "# Карта результатов обучения русской рукописи",
        "",
        f"Дата сборки: {PUBLICATION_DATE}.",
        "",
        "Карта связывает обещание главы с наблюдаемым действием читателя. Она",
        "предназначена для развивающего редактора и технического рецензента и не",
        "входит в основной текст книги.",
        "",
    ]
    for chapter in chapters:
        lines.extend(
            [
                f"## Глава {chapter['number']}. {chapter['title']}",
                "",
                "**Заявленные результаты:**",
                "",
            ]
        )
        outcomes = chapter["outcomes"]
        if not outcomes:
            raise ValueError(f"Chapter {chapter['number']} has no learning outcomes")
        lines.extend(f"- {outcome}" for outcome in outcomes)
        lines.extend(
            [
                "",
                "**Наблюдаемая точка применения:**",
                "",
                f"- Артефакт: {chapter['artifact']}",
                f"- Действие читателя: {chapter['practice']}",
            ]
        )
        if chapter["listings"]:
            lines.append(
                f"- Проверяемый материал: {len(chapter['listings'])} "
                f"листинг(а/ов) ({'; '.join(chapter['listings'])})."
            )
        if chapter["tables"]:
            lines.append(
                f"- Структурированное сравнение: {len(chapter['tables'])} "
                f"таблиц(а/ы) ({'; '.join(chapter['tables'])})."
            )
        if chapter["labs"]:
            lines.append(
                f"- Независимая проверка: лабораторная работа «{'; '.join(chapter['labs'])}»."
            )
        if chapter["labs"]:
            coverage = "артефакт, объяснение и независимая лабораторная проверка"
        elif chapter["listings"] and chapter["tables"]:
            coverage = "артефакт, исполняемый или проверяемый листинг и структурированное сравнение"
        elif chapter["listings"]:
            coverage = "артефакт и исполняемый или проверяемый листинг"
        elif chapter["tables"]:
            coverage = "артефакт и структурированное сравнение"
        else:
            coverage = "артефакт и действие переноса в практическом шаге"
        lines.extend(
            [
                "",
                f"**Статус покрытия:** {coverage}.",
                "",
                "**Критерий приемки:** читатель создал заявленный артефакт, "
                "воспроизвел практический шаг и может связать наблюдаемый "
                "результат с каждым обещанием главы.",
            ]
        )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


